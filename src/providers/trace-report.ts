import type { ScenarioTrace } from './trace.ts';

interface TraceDoc {
  fixture: { version: string; seed: number };
  client_timeout_ms: number;
  traces: ScenarioTrace[];
}

type StepOutcome = ScenarioTrace['steps'][number]['outcome'];

/** For successful calls, show what the provider said the entity looks like. */
function seen(o: Extract<StepOutcome, { kind: 'ok' }>): string {
  const body = o.body as { order?: Entity; shipment?: Entity; applied?: boolean };
  const e = body.order ?? body.shipment;
  if (e) return ` → ${e.address_id} v${e.version} ${e.status}`;
  return body.applied ? ' → applied' : '';
}
interface Entity {
  address_id: string;
  version: number;
  status: string;
}

const fmt = (o: StepOutcome) =>
  o.kind === 'ok'
    ? `ok ${o.status}${o.replayed ? ' (replayed)' : ''}${seen(o)}`
    : o.kind === 'rejected'
      ? `rejected ${o.status} ${o.code}`
      : `**UNKNOWN** (${o.reason}${o.code ? ` ${o.code}` : ''})`;

/** Human-readable summary of the generated traces. Generated; do not edit by hand. */
export function renderTraceSummary(doc: TraceDoc): string {
  const lines = [
    '# Phase 02 fault traces (generated)',
    '',
    `Generated by \`npm run traces\` from fixture \`${doc.fixture.version}\` seed ${doc.fixture.seed}, client timeout ${doc.client_timeout_ms} ms. Raw data: [phase-02-fault-traces.json](phase-02-fault-traces.json). **Do not edit by hand.**`,
    '',
    'The probe per provider: read → write → (if UNKNOWN: status query → retry once) → read → read. It is a fixed experiment, not a retry policy.',
    '',
    '| Scenario | Fault | Steps (outcome per step) | Final order address / version | Final carrier address / version | Mutations applied (order / carrier) |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const t of doc.traces) {
    const steps = t.steps.map((s) => `${s.probe}.${s.step}: ${fmt(s.outcome)}`).join('<br>');
    const o = t.after.order as { address_id: string; version: number; status: string };
    const c = t.after.shipment as { address_id: string; version: number; status: string };
    lines.push(
      `| ${t.scenario_id} ${t.title} | ${t.fault} | ${steps} | ${o.address_id} v${o.version} ${o.status} | ${c.address_id} v${c.version} ${c.status} | ${t.mutation_counts.order} / ${t.mutation_counts.carrier} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}
